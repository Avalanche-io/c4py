"""A folded range's ID list goes through merge, diff and patch with its range.

The shared range-data vector (c4 core ``c4m/testdata/range-data-vector/``,
c4 #159, regenerated by #161), vendored byte for byte from c4 commit
b82ec07. Ruled 2026-11-13 by the maintainer: "A frame id list is a part of
the c4m format, and is the same thing as a subdirectory being referenced by
it's ID on a parents directory line. Everything that you would expect of the
creation and retention of that subdirectory c4m file you would also expect
of the frame id list."

The rule: an output carries the ID list of every range entry it contains,
and no list for a range it does not. A list the inputs lack stays absent;
none is invented. Through 2026-11-13 c4py's ``merge``, ``patch_diff`` and
``Manifest.filter`` dropped every list, and ``apply_patch``, the decoder's
patch step and ``resolve_chain`` kept the list of a range the patch removed.

c4py has no sequence detector and no expander, so it starts from
``folded.c4m`` (as the README allows a port without a detector) and has no
expand rows. With no expander, no frame is ever made from a range: a range
whose list is not inline (``folded-no-lists.c4m``) stays one folded entry,
the "no list, no expansion" rule of c4 #160.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import pytest

from c4py.decoder import load
from c4py.diff import apply_patch, merge, patch_diff, resolve_chain
from c4py.encoder import dumps

VECTOR = Path(__file__).parent / "vectors" / "range-data-vector"


def _m(name: str):
    return load(str(VECTOR / name))


def _sha(text: str) -> str:
    return hashlib.sha512(text.encode("utf-8")).hexdigest()


def _merge(a: str, b: str) -> str:
    return dumps(merge(None, _m(a), _m(b))[0])


def _apply_add() -> str:
    patch = _m("add.c4m")  # its first line is plain.c4m's ID, read as a base
    patch.base = None
    return dumps(apply_patch(_m("plain.c4m"), patch))


def _resolve_remove() -> str:
    chain = _m("folded.c4m")
    chain.patch_sections = [_m("folded.c4m").entries, _m("remove.c4m").entries]
    return dumps(resolve_chain(chain))


# The README's "What a conforming implementation MUST do" table, the rows a
# port with no detector and no expander can run, plus filter, which Go's
# FilterByPath keeps lists through too (c4 #159).
OPERATIONS = {
    "merge folded with plain": (lambda: _merge("folded.c4m", "plain.c4m"), "merged.c4m"),
    "merge plain with folded": (lambda: _merge("plain.c4m", "folded.c4m"), "merged.c4m"),
    "merge folded with itself": (lambda: _merge("folded.c4m", "folded.c4m"), "folded.c4m"),
    "diff plain to folded": (lambda: patch_diff(_m("plain.c4m"), _m("folded.c4m")), "add.c4m"),
    "diff folded to no-plate": (
        lambda: patch_diff(_m("folded.c4m"), _m("no-plate.c4m")),
        "remove.c4m",
    ),
    "patch (resolve) add-chain": (lambda: dumps(_m("add-chain.c4m")), "folded.c4m"),
    "patch plain with add": (_apply_add, "folded.c4m"),
    "patch (resolve) remove-chain": (lambda: dumps(_m("remove-chain.c4m")), "no-plate.c4m"),
    "resolve_chain folded then remove": (_resolve_remove, "no-plate.c4m"),
    "filter folded to everything but plate": (
        lambda: dumps(_m("folded.c4m").filter(lambda p, e: not p.startswith("plate"))),
        "no-plate.c4m",
    ),
}


@pytest.mark.parametrize("op", list(OPERATIONS))
def test_operation_writes_the_vector_file(op):
    run, want = OPERATIONS[op]
    assert _sha(run()) == _sha((VECTOR / want).read_text()), f"{op} is not {want}"


def test_lists_never_change_a_description_id():
    for name in ("folded.c4m", "merged.c4m", "no-plate.c4m"):
        m = _m(name)
        assert m._range_data, name
        with_lists = m.compute_c4id()
        m._range_data = {}
        assert m.compute_c4id() == with_lists, name
    assert _m("folded.c4m").compute_c4id() == _m("folded-no-lists.c4m").compute_c4id()


def test_a_list_goes_only_with_a_range_the_output_holds():
    # A stray list the new side carries, for a range it does not hold: the
    # diff's removal line for that range takes no list.
    stale = _m("no-plate.c4m")
    stale._range_data = dict(_m("folded.c4m")._range_data)
    assert patch_diff(_m("folded.c4m"), stale) == (VECTOR / "remove.c4m").read_text()

    # A plain file whose bytes are the plate range's list has the list's C4
    # ID, but it is not a range, so no list goes with it.
    folded = _m("folded.c4m")
    plate = next(e for e in folded.entries if e.name == "plate.[1001-1004].exr")
    lone = _m("plain.c4m")
    lone.entries[0].c4id = plate.c4id  # other.txt
    lone._range_data = dict(folded._range_data)
    assert not lone.entries[0].is_sequence
    assert merge(None, lone, _m("plain.c4m"))[0]._range_data == {}


def test_a_range_without_its_list_stays_one_folded_entry():
    m = _m("folded-no-lists.c4m")
    assert m._range_data == {}
    ranges = [e for e in m.entries if e.is_sequence]
    assert [e.name for e in ranges] == ["plate.[1001-1004].exr", "shot.[001-003].exr"]
    # Nothing is invented: a merge, a diff or a filter of it carries no list.
    assert _merge("folded-no-lists.c4m", "plain.c4m").count("\n") == 6
    assert merge(None, m, _m("plain.c4m"))[0]._range_data == {}
    assert m.filter(lambda p, e: True)._range_data == {}
    assert patch_diff(_m("plain.c4m"), m).count("\n") == 6  # ID line + 5 entries
