"""Generate src/c4py/_printable.py from the shared printable table.

SafeName's printable test is pinned to one Unicode version so that a name's
encoding, and so its C4 ID, never depends on which Python encoded it. The
table is the shared text file every implementation embeds,
tests/vectors/safename-vector/printable-<version>.txt, a byte-for-byte copy
of c4 core's c4m/testdata/safename-vector/ (made there by gen_printable.go
from Go's unicode.IsPrint). This script turns it into Python source:

    python3 scripts/gen_printable.py

tests/test_printable_table.py fails if the generated module and the text
file disagree.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTOR = ROOT / "tests" / "vectors" / "safename-vector"
OUT = ROOT / "src" / "c4py" / "_printable.py"


def read_ranges(path: Path) -> list[tuple[int, int]]:
    """Parse the shared table: '#' comments, else one 'LO..HI' hex range."""
    ranges: list[tuple[int, int]] = []
    for n, line in enumerate(path.read_text(encoding="ascii").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        lo_s, sep, hi_s = line.partition("..")
        if not sep:
            raise ValueError(f"{path}:{n}: bad line {line!r}")
        lo, hi = int(lo_s, 16), int(hi_s, 16)
        if lo > hi or (ranges and lo <= ranges[-1][1]):
            raise ValueError(f"{path}:{n}: ranges must be sorted and disjoint")
        ranges.append((lo, hi))
    return ranges


def render(version: str, ranges: list[tuple[int, int]]) -> str:
    out = [
        "# Code generated by scripts/gen_printable.py; DO NOT EDIT.\n",
        '"""SafeName\'s printable code points, pinned to one Unicode version.\n',
        "\n",
        f"Generated from tests/vectors/safename-vector/printable-{version}.txt.\n",
        '"""\n',
        "\n",
        "# The Unicode version SafeName's printable test is pinned to.\n",
        f'PRINTABLE_UNICODE_VERSION = "{version}"\n',
        "\n",
        "# Printable code points as inclusive (lo, hi) ranges, sorted and disjoint.\n",
        "PRINTABLE_RANGES: tuple[tuple[int, int], ...] = (\n",
    ]
    for lo, hi in ranges:
        out.append(f"    (0x{lo:04X}, 0x{hi:04X}),\n")
    out.append(")\n")
    return "".join(out)


def main() -> int:
    version = (VECTOR / "unicode-version.txt").read_text(encoding="ascii").strip()
    ranges = read_ranges(VECTOR / f"printable-{version}.txt")
    OUT.write_text(render(version, ranges), encoding="utf-8")
    print(f"{len(ranges)} ranges, Unicode {version} -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
